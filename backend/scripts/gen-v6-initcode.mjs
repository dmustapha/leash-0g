// Stage F′ (FP-4 P1) — regenerate src/chain/v6-initcode.generated.ts from the
// Foundry artifact. The V6 account creationCode is COMMITTED into the backend (so
// the deployer can stay account-agnostic / EIP-170-safe) and hash-checked at
// module load. Run after any LeashAccountV6 recompile:
//   node scripts/gen-v6-initcode.mjs
// Then `npx tsc --noEmit` + the v6-initcode vitest must pass (they assert the
// embedded hash matches the artifact).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { keccak256 } from 'viem';

const here = dirname(fileURLToPath(import.meta.url));
const artifactPath = resolve(here, '../../contracts/out/LeashAccountV6.sol/LeashAccountV6.json');
const outPath = resolve(here, '../src/chain/v6-initcode.generated.ts');

const artifact = JSON.parse(readFileSync(artifactPath, 'utf8'));
const code = artifact?.bytecode?.object;
if (typeof code !== 'string' || !code.startsWith('0x')) {
  throw new Error(`gen-v6-initcode: artifact ${artifactPath} has no .bytecode.object`);
}
const hash = keccak256(code);

const out = `// GENERATED by scripts/gen-v6-initcode.mjs — DO NOT EDIT BY HAND.
// Source: contracts/out/LeashAccountV6.sol/LeashAccountV6.json (.bytecode.object).
// The hash-check in v6-initcode.ts asserts this blob against ARTIFACT_CREATION_CODE_HASH.
import type { Hex } from 'viem';

/** keccak256(V6_CREATION_CODE), recorded at generation time from the artifact. */
export const ARTIFACT_CREATION_CODE_HASH =
  '${hash}' as const;

/** The committed LeashAccountV6 creationCode (ctor-less deploy bytecode). */
export const V6_CREATION_CODE =
  '${code}' as Hex;
`;

writeFileSync(outPath, out);
console.log(`wrote ${outPath} (creationCode ${code.length} chars, hash ${hash})`);
